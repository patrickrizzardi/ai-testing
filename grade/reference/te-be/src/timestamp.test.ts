import { expect, test } from 'bun:test';
import { parseSpentAt } from './timestamp.ts';

// Tier: High (parser). Catches: wrong instant for an offset, leap-day and range mistakes, sub-millisecond rounding.
test.each([
  ['2026-03-14T18:30:00+01:00', Date.UTC(2026, 2, 14, 17, 30)],
  ['2026-03-14T18:30:00Z', Date.UTC(2026, 2, 14, 18, 30)],
  ['2026-03-14T18:30:00-05:30', Date.UTC(2026, 2, 14, 24, 0)],
  ['2026-03-14T18:30:00.5Z', Date.UTC(2026, 2, 14, 18, 30, 0, 500)],
  ['2026-03-31T23:59:59.999999999Z', Date.UTC(2026, 2, 31, 23, 59, 59, 999)],
  ['2028-02-29T00:00:00Z', Date.UTC(2028, 1, 29)],
  ['0000-01-01T00:00:00Z', -62_167_219_200_000],
])('accepts %s', (text, epochMs) => {
  expect(parseSpentAt(text)).toEqual({ ok: true, value: epochMs });
});

test.each([
  '2026-03-14',
  '2026-03-14T18:30:00',
  '2026-03-14t18:30:00Z',
  '2026-03-14T18:30:00z',
  '2026-03-14 18:30:00Z',
  '2026-03-14T18:30:00.Z',
  '2026-03-14T18:30:00.1234567890Z',
  '2026-03-14T18:30:00+0100',
  '2026-02-29T00:00:00Z',
  '2100-02-29T00:00:00Z',
  '2026-04-31T00:00:00Z',
  '2026-00-10T00:00:00Z',
  '2026-13-10T00:00:00Z',
  '2026-03-00T00:00:00Z',
  '2026-03-14T24:00:00Z',
  '2026-03-14T18:60:00Z',
  '2026-03-14T18:30:60Z',
  '2026-03-14T18:30:00+24:00',
  '2026-03-14T18:30:00+01:60',
  '2026-03-14T18:30:00Z\n',
])('rejects %p', (text) => {
  expect(parseSpentAt(text).ok).toBe(false);
});
